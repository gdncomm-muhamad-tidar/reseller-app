"""Generate src/ui/icons.gen.ts from assets/icons/*.svg (exported from Figma).
Monochrome icons get fill -> currentColor so <Icon color> can tint them;
multi-colour art (badge-gold, medallion, coin-gold) is kept as is. Run: python3 scripts/build-icons.py"""
import json, pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
KEEP = {'success-check', 'points-blibli', 'badge-gold', 'medallion', 'coin-gold', 'supergraphic', 'tier-gold', 'tier-classic', 'tier-platinum', 'tier-infinite', 'inspiration'}
out = {}
for f in sorted((root / 'assets/icons').glob('*.svg')):
    s = f.read_text()
    s = re.sub(r'\s(preserveAspectRatio|overflow|style)="[^"]*"', '', s)
    if f.stem not in KEEP:
        s = re.sub(r'(fill|stroke)="(?!none)[^"]*"', r'\1="currentColor"', s)
        s = re.sub(r'\s(fill|stroke)-opacity="[^"]*"', '', s)
    out[f.stem] = re.sub(r'>\s+<', '><', s).strip()
body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v)}' for k, v in out.items())
(root / 'src/ui/icons.gen.ts').write_text(
    '// Generated by scripts/build-icons.py from assets/icons (Figma: Reseller App Evaluation). Do not edit.\n'
    f'export const SVG = {{\n{body},\n}} as const;\nexport type SvgName = keyof typeof SVG;\n')
print(len(out), 'icons')
